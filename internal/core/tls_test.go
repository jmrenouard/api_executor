func TestCertManagerAutoGeneratesSelfSignedCertificate(t *testing.T) {
	// Arrange
	tmpDir := t.TempDir()
	tlsCfg := DefaultTLSConfig()
	tlsCfg.CertFile = filepath.Join(tmpDir, "certs", "server.crt")
	tlsCfg.KeyFile = filepath.Join(tmpDir, "certs", "server.key")
	tlsCfg.Organization = "Test Admin Org"
	tlsCfg.ValidityDays = 90
	tlsCfg.Hosts = []string{"localhost", "127.0.0.1", "admin.internal.local"}

	// Act
	cm, err := NewCertManager(tlsCfg, "192.168.1.50")
	if err != nil {
		t.Fatalf("NewCertManager failed: %v", err)
	}

	// Assert: files created on disk
	if _, err := os.Stat(tlsCfg.CertFile); err != nil {
		t.Errorf("expected cert file to exist at %s: %v", tlsCfg.CertFile, err)
	}
	if _, err := os.Stat(tlsCfg.KeyFile); err != nil {
		t.Errorf("expected key file to exist at %s: %v", tlsCfg.KeyFile, err)
	}

	info := cm.Info()
	if !info.Enabled {
		t.Errorf("expected info.Enabled to be true")
	}
	if !info.AutoGenerated {
		t.Errorf("expected info.AutoGenerated to be true")
	}
	if !strings.Contains(info.Subject, "Test Admin Org") {
		t.Errorf("expected Subject to contain organization 'Test Admin Org', got %q", info.Subject)
	}
	if info.Expired {
		t.Errorf("expected newly generated cert not to be expired")
	}
	if info.DaysRemaining < 89 || info.DaysRemaining > 91 {
		t.Errorf("expected DaysRemaining around 90, got %d", info.DaysRemaining)
	}
	if info.FingerprintSHA256 == "" {
		t.Errorf("expected non-empty SHA-256 fingerprint")
	}

	// Check SANs include DNS names and IP addresses including serverHost
	foundDNS := false
	for _, dns := range info.DNSNames {
		if dns == "admin.internal.local" {
			foundDNS = true
			break
		}
	}
	if !foundDNS {
		t.Errorf("expected DNSNames to contain 'admin.internal.local', got %v", info.DNSNames)
	}

	foundIP := false
	for _, ip := range info.IPAddresses {
		if ip == "192.168.1.50" {
			foundIP = true
			break
		}
	}
	if !foundIP {
		t.Errorf("expected IPAddresses to contain serverHost '192.168.1.50', got %v", info.IPAddresses)
	}
}

func TestCertManagerReusesExistingValidCertificate(t *testing.T) {
	// Arrange
	tmpDir := t.TempDir()
	tlsCfg := DefaultTLSConfig()
	tlsCfg.CertFile = filepath.Join(tmpDir, "server.crt")
	tlsCfg.KeyFile = filepath.Join(tmpDir, "server.key")

	cm1, err := NewCertManager(tlsCfg, "127.0.0.1")
	if err != nil {
		t.Fatalf("first NewCertManager failed: %v", err)
	}
	serial1 := cm1.Info().SerialNumber
	fp1 := cm1.Info().FingerprintSHA256

	// Act: create a second CertManager pointing to the same files
	cm2, err := NewCertManager(tlsCfg, "127.0.0.1")
	if err != nil {
		t.Fatalf("second NewCertManager failed: %v", err)
	}

	// Assert: certificate was loaded from disk, not overwritten
	if cm2.Info().SerialNumber != serial1 {
		t.Errorf("expected serial number %s to be reused, got %s", serial1, cm2.Info().SerialNumber)
	}
	if cm2.Info().FingerprintSHA256 != fp1 {
		t.Errorf("expected fingerprint %s to be reused, got %s", fp1, cm2.Info().FingerprintSHA256)
	}
	if cm2.Info().AutoGenerated {
		t.Errorf("expected AutoGenerated=false when reusing existing certificate from disk")
	}
}

func TestCertManagerAutoRenewsExpiredCertificate(t *testing.T) {
	// Arrange: write an already-expired certificate to disk
	tmpDir := t.TempDir()
	certFile := filepath.Join(tmpDir, "expired.crt")
	keyFile := filepath.Join(tmpDir, "expired.key")

	expiredSerial := big.NewInt(42)
	writeTestCert(t, certFile, keyFile, expiredSerial, time.Now().Add(-48*time.Hour), time.Now().Add(-24*time.Hour))

	tlsCfg := DefaultTLSConfig()
	tlsCfg.CertFile = certFile
	tlsCfg.KeyFile = keyFile
	tlsCfg.AutoGenerate = true

	// Act
	cm, err := NewCertManager(tlsCfg, "localhost")
	if err != nil {
		t.Fatalf("NewCertManager failed to auto-renew expired cert: %v", err)
	}

	// Assert
	info := cm.Info()
	if info.Expired {
		t.Errorf("expected renewed certificate not to be expired")
	}
	if info.SerialNumber == expiredSerial.String() {
		t.Errorf("expected new serial number after auto-renewal, still got %s", info.SerialNumber)
	}
	if !info.AutoGenerated {
		t.Errorf("expected AutoGenerated=true after auto-renewing expired cert")
	}
}

