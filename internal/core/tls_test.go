func TestLoadConfigDefaultsToHTTPS(t *testing.T) {
	// Arrange: minimal config without explicit tls section
	tmpDir := t.TempDir()
	cfgPath := filepath.Join(tmpDir, "config.yaml")
	err := os.WriteFile(cfgPath, []byte(`
server:
  port: 8080
  host: "0.0.0.0"
`), 0600)
	if err != nil {
		t.Fatalf("failed to write config: %v", err)
	}

	// Act
	cfg, err := LoadConfig(cfgPath)
	if err != nil {
		t.Fatalf("LoadConfig failed: %v", err)
	}

	// Assert: HTTPS/TLS must be enabled by default with auto-generation enabled
	if !cfg.Server.TLS.Enabled {
		t.Errorf("expected TLS.Enabled to default to true, got false")
	}
	if !cfg.Server.TLS.AutoGenerate {
		t.Errorf("expected TLS.AutoGenerate to default to true, got false")
	}
	if cfg.Server.TLS.CertFile == "" || cfg.Server.TLS.KeyFile == "" {
		t.Errorf("expected default cert/key paths to be populated, got cert=%q key=%q", cfg.Server.TLS.CertFile, cfg.Server.TLS.KeyFile)
	}
	if cfg.Server.TLS.ValidityDays != 365 {
		t.Errorf("expected default ValidityDays=365, got %d", cfg.Server.TLS.ValidityDays)
	}
	if cfg.Server.TLS.MinVersion != "1.2" {
		t.Errorf("expected default MinVersion=1.2, got %q", cfg.Server.TLS.MinVersion)
	}
}

