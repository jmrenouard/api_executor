// CertificateInfo holds public metadata about the active TLS certificate.
type CertificateInfo struct {
	Enabled           bool      `json:"enabled"`
	AutoGenerated     bool      `json:"auto_generated"`
	CertFile          string    `json:"cert_file,omitempty"`
	KeyFile           string    `json:"key_file,omitempty"`
	Subject           string    `json:"subject,omitempty"`
	Issuer            string    `json:"issuer,omitempty"`
	SerialNumber      string    `json:"serial_number,omitempty"`
	NotBefore         time.Time `json:"not_before,omitempty"`
	NotAfter          time.Time `json:"not_after,omitempty"`
	DaysRemaining     int       `json:"days_remaining"`
	Expired           bool      `json:"expired"`
	DNSNames          []string  `json:"dns_names,omitempty"`
	IPAddresses       []string  `json:"ip_addresses,omitempty"`
	FingerprintSHA256 string    `json:"fingerprint_sha256,omitempty"`
	MinVersion        string    `json:"min_version,omitempty"`
	MTLS              bool      `json:"mtls"`
}

// CertManager manages TLS certificate lifecycle, auto-generation, inspection, and live rotation.
type CertManager struct {
	mu         sync.RWMutex
	cfg        TLSConfig
	serverHost string
	cert       *tls.Certificate
	certPEM    []byte
	clientCAs  *x509.CertPool
	info       CertificateInfo
}

// NewCertManager creates and initializes a CertManager from the given TLSConfig.
func NewCertManager(cfg TLSConfig, serverHost string) (*CertManager, error) {
	cm := &CertManager{
		cfg:        cfg,
		serverHost: serverHost,
	}

	if !cfg.Enabled {
		cm.info = CertificateInfo{
			Enabled: false,
		}
		return cm, nil
	}

	if cfg.MinVersion == "" {
		cm.cfg.MinVersion = "1.2"
	}
	if cm.cfg.MinVersion != "1.2" && cm.cfg.MinVersion != "1.3" {
		return nil, fmt.Errorf("unsupported TLS min_version %q (must be '1.2' or '1.3')", cm.cfg.MinVersion)
	}

	if cm.cfg.ValidityDays < 0 {
		return nil, fmt.Errorf("validity_days must be positive, got %d", cm.cfg.ValidityDays)
	}
	if cm.cfg.ValidityDays == 0 {
		cm.cfg.ValidityDays = 365
	}

	if cm.cfg.CertFile == "" || cm.cfg.KeyFile == "" {
		return nil, errors.New("tls cert_file and key_file must be specified when TLS is enabled")
	}

	if cm.cfg.ClientCAFile != "" {
		caPEM, err := os.ReadFile(cm.cfg.ClientCAFile)
		if err != nil {
			return nil, fmt.Errorf("failed to read client_ca_file %q: %w", cm.cfg.ClientCAFile, err)
		}
		pool := x509.NewCertPool()
		if !pool.AppendCertsFromPEM(caPEM) {
			return nil, fmt.Errorf("failed to parse client CA certificate from %q", cm.cfg.ClientCAFile)
		}
		cm.clientCAs = pool
	}

	if err := cm.loadOrGenerate(); err != nil {
		return nil, err
	}

	return cm, nil
}

func (cm *CertManager) loadOrGenerate() error {
	certExists := fileExists(cm.cfg.CertFile)
	keyExists := fileExists(cm.cfg.KeyFile)

	if certExists || keyExists {
		if !certExists || !keyExists {
			return fmt.Errorf("incomplete TLS keypair on disk (cert exists=%v, key exists=%v)", certExists, keyExists)
		}
		tlsCert, leaf, certPEM, err := loadKeyPairFromDisk(cm.cfg.CertFile, cm.cfg.KeyFile)
		if err != nil {
			return fmt.Errorf("failed to load existing TLS certificate: %w", err)
		}

		// Check expiration
		if time.Now().After(leaf.NotAfter) {
			if !cm.cfg.AutoGenerate {
				return fmt.Errorf("TLS certificate %q expired at %s and auto_generate is disabled", cm.cfg.CertFile, leaf.NotAfter.Format(time.RFC3339))
			}
			return cm.generateAndStore()
		}

		cm.mu.Lock()
		cm.cert = tlsCert
		cm.certPEM = certPEM
		cm.info = buildCertificateInfo(cm.cfg, leaf, certPEM, false, cm.clientCAs != nil)
		cm.mu.Unlock()
		return nil
	}

	if !cm.cfg.AutoGenerate {
		return fmt.Errorf("TLS certificate files (%s, %s) not found and auto_generate is disabled", cm.cfg.CertFile, cm.cfg.KeyFile)
	}

	return cm.generateAndStore()
}

func (cm *CertManager) generateAndStore() error {
	priv, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return fmt.Errorf("failed to generate ECDSA private key: %w", err)
	}

	serialLimit := new(big.Int).Lsh(big.NewInt(1), 128)
	serialNumber, err := rand.Int(rand.Reader, serialLimit)
	if err != nil {
		return fmt.Errorf("failed to generate certificate serial number: %w", err)
	}

	org := cm.cfg.Organization
	if org == "" {
		org = "Go Admin Tool"
	}

	dnsNames, ipAddrs := collectSANs(cm.cfg.Hosts, cm.serverHost)
	now := time.Now().UTC()
	notBefore := now.Add(-5 * time.Minute)
	notAfter := now.Add(time.Duration(cm.cfg.ValidityDays) * 24 * time.Hour)

	commonName := "localhost"
	if len(dnsNames) > 0 {
		commonName = dnsNames[0]
	}

	tmpl := x509.Certificate{
		SerialNumber: serialNumber,
		Subject: pkix.Name{
			Organization: []string{org},
			CommonName:   commonName,
		},
		NotBefore:             notBefore,
		NotAfter:              notAfter,
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment | x509.KeyUsageCertSign,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		IsCA:                  true,
		DNSNames:              dnsNames,
		IPAddresses:           ipAddrs,
	}

	derBytes, err := x509.CreateCertificate(rand.Reader, &tmpl, &tmpl, &priv.PublicKey, priv)
	if err != nil {
		return fmt.Errorf("failed to create self-signed X.509 certificate: %w", err)
	}

	certPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: derBytes})
	keyDER, err := x509.MarshalECPrivateKey(priv)
	if err != nil {
		return fmt.Errorf("failed to marshal ECDSA private key: %w", err)
	}
	keyPEM := pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: keyDER})

	if err := os.MkdirAll(filepath.Dir(cm.cfg.CertFile), 0755); err != nil {
		return fmt.Errorf("failed to create certificate directory: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(cm.cfg.KeyFile), 0755); err != nil {
		return fmt.Errorf("failed to create key directory: %w", err)
	}

	if err := os.WriteFile(cm.cfg.CertFile, certPEM, 0644); err != nil {
		return fmt.Errorf("failed to write certificate file: %w", err)
	}
	if err := os.WriteFile(cm.cfg.KeyFile, keyPEM, 0600); err != nil {
		return fmt.Errorf("failed to write private key file: %w", err)
	}

	tlsCert, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		return fmt.Errorf("failed to load generated keypair: %w", err)
	}
	leaf, err := x509.ParseCertificate(derBytes)
	if err != nil {
		return fmt.Errorf("failed to parse generated leaf certificate: %w", err)
	}
	tlsCert.Leaf = leaf

	cm.mu.Lock()
	cm.cert = &tlsCert
	cm.certPEM = certPEM
	cm.info = buildCertificateInfo(cm.cfg, leaf, certPEM, true, cm.clientCAs != nil)
	cm.mu.Unlock()

	return nil
}

// Rotate regenerates a fresh self-signed certificate and updates the active certificate in-place.
func (cm *CertManager) Rotate() (CertificateInfo, error) {
	if !cm.cfg.Enabled {
		return CertificateInfo{Enabled: false}, errors.New("cannot rotate certificate when TLS is disabled")
	}
	if err := cm.generateAndStore(); err != nil {
		return CertificateInfo{}, err
	}
	return cm.Info(), nil
}

// Info returns the metadata of the current TLS certificate.
func (cm *CertManager) Info() CertificateInfo {
	cm.mu.RLock()
	defer cm.mu.RUnlock()
	return cm.info
}

// CertPEM returns the PEM-encoded public certificate bytes.
func (cm *CertManager) CertPEM() ([]byte, error) {
	cm.mu.RLock()
	defer cm.mu.RUnlock()
	if !cm.cfg.Enabled || len(cm.certPEM) == 0 {
		return nil, errors.New("TLS certificate is not available")
	}
	out := make([]byte, len(cm.certPEM))
	copy(out, cm.certPEM)
	return out, nil
}

// TLSConfig builds a standard library *tls.Config with dynamic certificate lookup for live rotation.
func (cm *CertManager) TLSConfig() (*tls.Config, error) {
	if !cm.cfg.Enabled {
		return nil, errors.New("TLS is not enabled")
	}

	minVer := uint16(tls.VersionTLS12)
	if cm.cfg.MinVersion == "1.3" {
		minVer = tls.VersionTLS13
	}

	stdCfg := &tls.Config{
		MinVersion: minVer,
		GetCertificate: func(_ *tls.ClientHelloInfo) (*tls.Certificate, error) {
			cm.mu.RLock()
			defer cm.mu.RUnlock()
			if cm.cert == nil {
				return nil, errors.New("no TLS certificate loaded")
			}
			return cm.cert, nil
		},
	}

	if cm.clientCAs != nil {
		stdCfg.ClientCAs = cm.clientCAs
		stdCfg.ClientAuth = tls.RequireAndVerifyClientCert
	}

	return stdCfg, nil
}

func loadKeyPairFromDisk(certFile, keyFile string) (*tls.Certificate, *x509.Certificate, []byte, error) {
	certPEM, err := os.ReadFile(certFile)
	if err != nil {
		return nil, nil, nil, err
	}
	keyPEM, err := os.ReadFile(keyFile)
	if err != nil {
		return nil, nil, nil, err
	}
	tlsCert, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		return nil, nil, nil, err
	}
	if len(tlsCert.Certificate) == 0 {
		return nil, nil, nil, errors.New("empty certificate chain")
	}
	leaf, err := x509.ParseCertificate(tlsCert.Certificate[0])
	if err != nil {
		return nil, nil, nil, err
	}
	tlsCert.Leaf = leaf
	return &tlsCert, leaf, certPEM, nil
}

func buildCertificateInfo(cfg TLSConfig, leaf *x509.Certificate, certPEM []byte, autoGen bool, mtls bool) CertificateInfo {
	sum := sha256.Sum256(leaf.Raw)
	fp := strings.ToUpper(hex.EncodeToString(sum[:]))

	var ipStrings []string
	for _, ip := range leaf.IPAddresses {
		ipStrings = append(ipStrings, ip.String())
	}

	now := time.Now()
	expired := now.After(leaf.NotAfter)
	daysRemaining := int(leaf.NotAfter.Sub(now).Hours() / 24)
	if daysRemaining < 0 {
		daysRemaining = 0
	}

	return CertificateInfo{
		Enabled:           true,
		AutoGenerated:     autoGen,
		CertFile:          cfg.CertFile,
		KeyFile:           cfg.KeyFile,
		Subject:           leaf.Subject.String(),
		Issuer:            leaf.Issuer.String(),
		SerialNumber:      leaf.SerialNumber.String(),
		NotBefore:         leaf.NotBefore,
		NotAfter:          leaf.NotAfter,
		DaysRemaining:     daysRemaining,
		Expired:           expired,
		DNSNames:          leaf.DNSNames,
		IPAddresses:       ipStrings,
		FingerprintSHA256: fp,
		MinVersion:        cfg.MinVersion,
		MTLS:              mtls,
	}
}

func collectSANs(hosts []string, serverHost string) ([]string, []net.IP) {
	dnsSet := make(map[string]struct{})
	ipSet := make(map[string]net.IP)

	candidates := append([]string{"localhost", "127.0.0.1", "::1"}, hosts...)
	if serverHost != "" && serverHost != "0.0.0.0" && serverHost != "::" {
		candidates = append(candidates, serverHost)
	}

	var dnsNames []string
	var ipAddrs []net.IP

	for _, h := range candidates {
		h = strings.TrimSpace(h)
		if h == "" {
			continue
		}
		if ip := net.ParseIP(h); ip != nil {
			key := ip.String()
			if _, exists := ipSet[key]; !exists {
				ipSet[key] = ip
				ipAddrs = append(ipAddrs, ip)
			}
		} else {
			if _, exists := dnsSet[h]; !exists {
				dnsSet[h] = struct{}{}
				dnsNames = append(dnsNames, h)
			}
		}
	}

	return dnsNames, ipAddrs
}

func fileExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}
